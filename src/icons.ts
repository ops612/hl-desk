export type IconName = keyof typeof PATHS;

export function icon(name: IconName, size = 14, cls = "ico"): string {
  return `<svg class="${cls}" width="${size}" height="${size}" viewBox="0 0 24 24" aria-hidden="true" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">${PATHS[name]}</svg>`;
}

/** Puts the icon named by data-icon before the element's text (static markup in index.html). */
export function fillIcons(root: ParentNode = document): void {
  for (const el of root.querySelectorAll<HTMLElement>("[data-icon]")) {
    el.insertAdjacentHTML("afterbegin", icon(el.dataset.icon as IconName));
    el.removeAttribute("data-icon");
  }
}
